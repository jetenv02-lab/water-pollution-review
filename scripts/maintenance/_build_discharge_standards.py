HEADERS = ["業別", "水質項目", "限值", "單位", "適用條件", "施行日期", "備註/來源"]


def write_sheet(wb, sheet_name, data, source_note):
    """建/更新一個分頁, 寫入 HEADERS + data。"""
    if sheet_name in wb.sheetnames:
        del wb[sheet_name]
    ws = wb.create_sheet(sheet_name)
    ws.append(HEADERS)
    for row in data:
        # 補齊備註欄
        if len(row) < 7:
            row = list(row) + [""] * (7 - len(row))
        row = list(row)
        if not row[6]:
            row[6] = source_note
        ws.append(row)
    print(f"[OK] 分頁 {sheet_name}: {len(data)} 條")



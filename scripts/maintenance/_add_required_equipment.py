def main():
    wb = openpyxl.load_workbook("規則庫.xlsx")
    ws = wb["_槽體學理"]

    # 加表頭 AB (28)
    if ws.cell(1, 28).value != "必備機具":
        ws.cell(1, 28).value = "必備機具"

    updated = 0
    missing = []
    for r in range(2, ws.max_row + 1):
        tank = ws.cell(r, 1).value
        if not tank:
            continue
        eq = RULES.get(tank, None)
        if eq is None:
            missing.append(tank)
            continue
        ws.cell(r, 28).value = eq
        updated += 1

    wb.save("規則庫.xlsx")
    print("已更新 {} 列 _槽體學理".format(updated))
    if missing:
        print("未在 RULES 定義:", missing)


if __name__ == "__main__":
    main()
